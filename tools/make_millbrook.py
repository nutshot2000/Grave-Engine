"""Generate scenes/millbrook-waterwheel.txt: a working overshot waterwheel.

A mill pond up on the hill drains through a sluice gate into a wooden flume,
which pours onto the top of the wheel. The water's weight in the buckets turns
the wheel; it spills into a stone-lined tailrace and runs to the lower pond.
The stone pier carrying the axle and the mill's interior are in the plane
behind. Everything is real material; colours are surface paint.

py tools/make_waterwheel.py   (builds the wheel asset)
py tools/make_millbrook.py    (writes this scene)
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from asset_builder import FONT  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
W, H = 400, 230
AX, AY = 196, 112          # the wheel's axle in the world (radius 50 with buckets)
GROUND = 178
HILL = 64                  # top of the hill the mill pond sits on
FLUME_Y = 58               # the flume's floor
MX = AX + 62               # the mill house's left wall

lines, paint, grid = [], {}, {}

def add(s):
    lines.append(s)

def rect(mat, x, y, w, h):
    add(f"rect {mat} {x} {y} {w} {h}")
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            if 0 <= xx < W and 0 <= yy < H:
                grid[(xx, yy)] = mat

def tint(x, y, w, h, color):
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            paint[(xx, yy)] = color

def dot(x, y, color):
    paint[(x, y)] = color

def text(x, y, s, color):
    for i, c in enumerate(s):
        for dy, row in enumerate(FONT[c]):
            for dx, on in enumerate(row):
                if on == "1":
                    dot(x + i * 4 + dx, y + dy, color)

def noise(x, y):
    return ((x * 73856093) ^ (y * 19349663)) % 97

# Palette: one dark outline per material, a body colour, a lighter edge.
WOOD_DARK, WOOD, WOOD_LIGHT = "#2b1d15", "#6e4a2f", "#9c6d43"
STONE_DARK, STONE, STONE_LIGHT = "#5b5d63", "#7f8188", "#a9abaf"
GRASS, GRASS_DARK = "#5f8f3e", "#47702e"
DIRT_DARK = "#5c3f2a"
GOLD = "#e5ba63"

add("# Millbrook: a working overshot waterwheel. Press Play.")
add("# The pond drains along the flume; the water's weight in the buckets turns the wheel.")
add("# Generated by tools/make_millbrook.py (the wheel: tools/make_waterwheel.py).")
add(f"size {W} {H}")
add("seed 21")
add("fill air")
add("sky #6f9ccc #f2d9a8")
add("layer mountains #8796ad depth 0.12 y 150 height 70 seed 3")
add("layer forest #4f6b4a depth 0.3 y 168 height 28 seed 11")

# Ground: earth with a grass skin and darker strata, bedrock below.
rect("dirt", 0, GROUND, W, H - GROUND)
rect("stone", 0, H - 8, W, 8)

# The hill, sloping down to the valley floor on its right.
for y in range(HILL, GROUND):
    right = 128 + (y - HILL) // 7
    rect("dirt", 0, y, right, 1)

# The mill pond: a stone basin on the hill, filled with real (finite) water.
rect("stone", 0, 26, 3, HILL - 26)
rect("stone", 0, HILL - 4, 126, 4)
rect("stone", 120, 26, 6, HILL - 26)          # the dam
rect("water", 3, 30, 117, HILL - 34)
tint(0, 26, 3, HILL - 26, STONE)
tint(0, HILL - 4, 126, 4, STONE)
tint(120, 26, 6, HILL - 26, STONE)
for x in range(0, 126):
    dot(x, HILL - 4, STONE_LIGHT)
for y in range(26, HILL, 3):                  # mortar courses on the dam
    for x in range(120, 126):
        dot(x, y, STONE_DARK)
for x in (120, 125):
    tint(x, 26, 1, HILL - 26, STONE_DARK)

# Sluice: an opening at the foot of the dam, under a wooden gate frame.
rect("air", 120, HILL - 10, 6, 6)
rect("wood", 118, 14, 2, 14)
rect("wood", 126, 14, 2, 14)
rect("wood", 116, 12, 14, 2)
for x, y, w, h in ((118, 14, 2, 14), (126, 14, 2, 14), (116, 12, 14, 2)):
    tint(x, y, w, h, WOOD)
    tint(x, y, w, 1, WOOD_LIGHT)
rect("iron", 122, 8, 2, 4)                    # the gate's lifting wheel
rect("iron", 120, 7, 6, 1)
tint(120, 7, 6, 1, "#2c3236")
tint(122, 8, 2, 4, "#59636a")

# The flume: a plank trough from the sluice to just past the top of the wheel.
END = AX + 10
rect("wood", 126, FLUME_Y, END - 126, 3)       # floor
tint(126, FLUME_Y, END - 126, 1, WOOD_LIGHT)
tint(126, FLUME_Y + 1, END - 126, 1, WOOD)
tint(126, FLUME_Y + 2, END - 126, 1, WOOD_DARK)
for x in range(130, END, 9):                   # plank joints
    dot(x, FLUME_Y + 1, WOOD_DARK)
# (The flume's side boards are in the plane behind: in front they'd dam the water.)
# Trestle legs between the hill and the wheel's sweep, with a cross brace.
for x in (136, 142):
    rect("wood", x, FLUME_Y + 3, 2, GROUND - FLUME_Y - 3)
    tint(x, FLUME_Y + 3, 2, GROUND - FLUME_Y - 3, WOOD)
    tint(x, FLUME_Y + 3, 1, GROUND - FLUME_Y - 3, WOOD_DARK)
for k in range(0, 60, 2):
    x, y = 136 + (k * 6) // 60, FLUME_Y + 8 + k
    if (x, y) not in grid:
        rect("wood", x, y, 1, 1)
        dot(x, y, WOOD_DARK)

# Wheel pit and tailrace: a stone-lined channel under the wheel, falling
# gently to the right into the lower pond.
PIT_X0, PIT_X1 = AX - 56, AX + 60
for x in range(PIT_X0, W - 4):
    depth = 6 + max(0, (x - PIT_X1) // 14)
    rect("air", x, GROUND, 1, depth)
    rect("stone", x, GROUND + depth, 1, 2)
    tint(x, GROUND + depth, 1, 1, STONE_LIGHT if noise(x, 0) % 5 else STONE)
    tint(x, GROUND + depth + 1, 1, 1, STONE_DARK)
rect("stone", PIT_X0 - 2, GROUND, 2, 8)
tint(PIT_X0 - 2, GROUND, 2, 8, STONE)
# The lower pond at the far right.
rect("air", W - 64, GROUND, 60, 22)
rect("stone", W - 66, GROUND + 22, 66, 2)
rect("stone", W - 4, GROUND, 4, 24)
tint(W - 66, GROUND + 22, 66, 2, STONE_DARK)
tint(W - 4, GROUND, 4, 24, STONE)
rect("water", W - 63, GROUND + 15, 59, 7)

# The mill: stone walls with coursed blocks, tiled roof, door, windows, sign.
rect("stone", MX, GROUND - 60, 74, 60)
for y in range(GROUND - 60, GROUND):
    for x in range(MX, MX + 74):
        course = (y - (GROUND - 60)) // 4
        joint = (x - MX + (course % 2) * 6) % 12 == 0 or (y - (GROUND - 60)) % 4 == 0
        n = noise(x, y)
        dot(x, y, STONE_DARK if joint else (STONE_LIGHT if n < 12 else STONE))
tint(MX, GROUND - 60, 1, 60, STONE_DARK)
tint(MX + 73, GROUND - 60, 1, 60, STONE_DARK)
# Roof: overlapping courses of clay tiles.
for k in range(16):
    x, y, w = MX - 6 + k * 3, GROUND - 62 - k * 2, 86 - k * 6
    rect("brick", x, y, w, 2)
    for xx in range(x, x + w):
        dot(xx, y, "#a5533a" if (xx + k) % 5 else "#6d2c1f")
        dot(xx, y + 1, "#7a3b2a")
rect("brick", MX + 52, GROUND - 92, 6, 18)     # chimney
tint(MX + 52, GROUND - 92, 6, 18, "#8f4a34")
tint(MX + 52, GROUND - 92, 6, 1, "#c27052")
# Door: planks with iron straps, in a stone arch.
rect("wood", MX + 30, GROUND - 24, 14, 24)
for y in range(GROUND - 24, GROUND):
    for x in range(MX + 30, MX + 44):
        dot(x, y, WOOD_DARK if (x - MX - 30) % 4 == 0 else WOOD)
for y in (GROUND - 19, GROUND - 6):
    tint(MX + 30, y, 14, 1, "#2c3236")
dot(MX + 41, GROUND - 12, GOLD)
tint(MX + 29, GROUND - 25, 16, 1, STONE_DARK)
# Windows with warm light inside (lamp glass) and wooden frames.
for wx in (MX + 8, MX + 54):
    rect("lamp_glass", wx, GROUND - 44, 10, 10)
    tint(wx, GROUND - 44, 10, 10, "#f2c46a")
    for x in range(wx, wx + 10):
        dot(x, GROUND - 40, WOOD_DARK)
    for y in range(GROUND - 44, GROUND - 34):
        dot(wx + 5, y, WOOD_DARK)
    tint(wx - 1, GROUND - 45, 12, 1, WOOD_DARK)
    tint(wx - 1, GROUND - 34, 12, 1, WOOD_DARK)
# Sign board on two brackets.
rect("wood", MX + 13, GROUND - 56, 48, 9)
tint(MX + 13, GROUND - 56, 48, 9, WOOD_DARK)
tint(MX + 14, GROUND - 55, 46, 7, WOOD)
text(MX + 19, GROUND - 54, "MILLBROOK", GOLD)

# The wheel itself (asset: pivot at its bottom centre, axle 55.5 cells above).
add(f"asset ../assets/workshop/millbrook_waterwheel.asset {AX} {AY + 55} as wheel")

# Grass on every open earth surface; dark strata in the soil.
for x in range(W):
    for y in range(H):
        if grid.get((x, y)) == "dirt":
            above = grid.get((x, y - 1), "air")
            if above == "air":
                dot(x, y, GRASS)
                dot(x, y + 1, GRASS_DARK)
                if noise(x, y) % 7 == 0 and grid.get((x, y - 1), "air") == "air":
                    rect("plant" if False else "dirt", x, y - 1, 1, 1)
                    dot(x, y - 1, GRASS_DARK)
            elif noise(x, y) % 23 == 0:
                dot(x, y, DIRT_DARK)

# Fixed terrain: the hill, dam, flume, mill and ground don't collapse.
add(f"anchor 0 {HILL - 4} 146 {GROUND - HILL + 4}")   # hill and pond floor (not the water)
add(f"anchor 0 26 3 {HILL - 26}")
add(f"anchor 120 26 6 {HILL - 26 - 10}")
add("anchor 116 7 14 21")                            # the sluice gate frame
add(f"anchor 126 {FLUME_Y - 4} {END - 126} 7")          # the flume
add(f"anchor 136 {FLUME_Y} 8 {GROUND - FLUME_Y}")
add(f"anchor {MX - 6} {GROUND - 94} 86 94")
add(f"anchor 0 {GROUND} {W} {H - GROUND}")

out = lines[:]
out.append("")
out.append("# Generated surface paint: the materials underneath are unchanged.")
for (x, y), c in sorted(paint.items(), key=lambda p: (p[0][1], p[0][0])):
    if grid.get((x, y), "air") not in ("air", "water"):
        out.append(f"paint {x} {y} {c}")

# Behind the wheel: the stone pier and its iron bearing, and the mill's dim interior.
back = [
    "",
    "plane 1 behind",
    f"size {W} {H}",
    "fill air",
    f"rect dirt 0 {GROUND} {W} {H - GROUND}",
    f"rect stone {AX - 5} {AY - 2} 10 {GROUND - AY + 2}",
    f"rect stone {AX - 10} {GROUND - 10} 20 10",
    f"rect iron {AX - 4} {AY - 4} 8 7",
    f"rect wood {MX} {GROUND - 60} 74 60",
    f"rect wood 126 {FLUME_Y - 5} {END - 126} 8",
    f"anchor 0 {AY - 4} {W} {H - AY + 4}",
]
bpaint = {}
for y in range(AY - 2, GROUND):
    for x in range(AX - 5, AX + 5):
        bpaint[(x, y)] = STONE_DARK if (y - AY) % 5 == 0 or x in (AX - 5, AX + 4) else "#6c6e74"
for y in range(GROUND - 10, GROUND):
    for x in range(AX - 10, AX + 10):
        bpaint[(x, y)] = STONE_DARK if (y - GROUND) % 5 == 0 else "#6c6e74"
for y in range(AY - 4, AY + 3):
    for x in range(AX - 4, AX + 4):
        bpaint[(x, y)] = "#2c3236" if y in (AY - 4, AY + 2) else "#59636a"
for y in range(GROUND - 60, GROUND):
    for x in range(MX, MX + 74):
        bpaint[(x, y)] = "#3a2a1e" if (x - MX) % 8 else "#2b1d15"
for y in range(FLUME_Y - 5, FLUME_Y + 3):
    for x in range(126, END):
        top = y == FLUME_Y - 5
        bpaint[(x, y)] = WOOD_LIGHT if top else (WOOD_DARK if (x - 126) % 9 == 0 or y == FLUME_Y - 1 else "#5a3d27")
back += [f"paint {x} {y} {c}" for (x, y), c in sorted(bpaint.items(), key=lambda p: (p[0][1], p[0][0]))]
back.append("endplane")

(ROOT / "scenes/millbrook-waterwheel.txt").write_text("\n".join(out + back) + "\n", encoding="utf-8")
print("wrote scenes/millbrook-waterwheel.txt")
